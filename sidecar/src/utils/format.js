/**
 * Перетворює байти у мегабайти (MB) та форматує до двох знаків після коми.
 * @param {number} bytes - Кількість байтів.
 * @returns {string} - Відформатований рядок у мегабайтах (наприклад, "1.23").
 */
export function formatBytes(bytes) {
  return (bytes / 1024 / 1024).toFixed(2);
}
