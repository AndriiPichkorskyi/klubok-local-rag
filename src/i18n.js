export const LANGUAGE_KEY = "klubok.language";
export const SUPPORTED_LANGUAGES = ["uk", "en"];

export function normalizeLanguage(value) {
  const language = String(value || "").trim().toLowerCase();
  return language === "uk" || language.startsWith("uk-") ? "uk" : language === "en" || language.startsWith("en-") ? "en" : null;
}

function storedLanguage() {
  try {
    return normalizeLanguage(window.localStorage.getItem(LANGUAGE_KEY));
  } catch {
    return null;
  }
}

export function resolveInitialLanguage({
  stored = storedLanguage(),
  system = typeof navigator === "undefined"
    ? []
    : navigator.languages?.length
      ? navigator.languages
      : [navigator.language],
} = {}) {
  if (normalizeLanguage(stored)) return normalizeLanguage(stored);
  const languages = Array.isArray(system) ? system : [system];
  return languages.some((value) => normalizeLanguage(value) === "uk") ? "uk" : "en";
}

