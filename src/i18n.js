export async function setLanguage(language, { persist = true } = {}) {
  const normalized = normalizeLanguage(language) || "en";
  if (persist) {
    try {
      window.localStorage.setItem(LANGUAGE_KEY, normalized);
    } catch {
      /* Сховище може бути недоступним у тестовому середовищі. */
    }
  }
  if (typeof document !== "undefined") document.documentElement.lang = normalized;
  if (i18n.language !== normalized) await i18n.changeLanguage(normalized);
  return normalized;
}

if (typeof document !== "undefined") document.documentElement.lang = normalizeLanguage(i18n.language) || "en";

